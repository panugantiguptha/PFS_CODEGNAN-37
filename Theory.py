#difference between module,library and package
#Module:-A module in python is a single python file it consists python code.
#it typically consists of functions,classes, and variables that can be used in other python scripts, or programs.
#examples of modules math.py,random.py,or mymodule.py.


# Package:-
#1.A package in python is a directory containing one or more python modules and an __init__.py file.
#2.the __init__.py file can be empty or contain inialization code for the package.
#Examples for packages numpy,pandas and requests,Django.

# Library:-A module consists of both module and packages.
#example of library are numpy,pandas,mathplotlib.

